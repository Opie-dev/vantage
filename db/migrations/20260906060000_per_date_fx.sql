ALTER TABLE income_events DROP CONSTRAINT IF EXISTS income_events_fx_check;
ALTER TABLE income_events DROP COLUMN IF EXISTS fx_date;
ALTER TABLE income_events DROP COLUMN IF EXISTS fx_rate;
DROP INDEX IF EXISTS fx_rates_lookup_idx;
DROP TABLE IF EXISTS fx_rates;
